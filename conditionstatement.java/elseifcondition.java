public class elseifcondition{
    public static void main (String [] args){
        int mark = 59;

        if(mark >=90){
            System.out.println("Grade A+");

        }
        else if(mark >=70){
            System.out.println("Grade A");

        }
        else if(mark >=60){
            System.out.println("Grade B");
        }
        else{
            System.out.println("fail : Better luck next time");
        }
    }
}